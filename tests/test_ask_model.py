ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "config"))
import kilix_model  # noqa: E402

MODEL = kilix_model.ADMITTED[0]
WEIGHTS = MODEL.weights.sha256

# Stands in for plebian-model-sizer: echoes the request with one verdict.
SIZER = r'''#!/usr/bin/env python3
import hashlib, json, os, sys
raw = sys.stdin.buffer.read()
request = json.loads(raw)
verdict = os.environ.get("FAKE_SIZER_VERDICT", "estimated-fit")
rows = [dict(row, verdict=verdict, required_ram_bytes=7, avatar_budget_bytes=9) for row in request["models"]]
print(json.dumps({"schema": "plebian.models.avatar-chat-sizing/v1-development",
                  "request_sha256": hashlib.sha256(raw).hexdigest(), "resource_source": "live",
                  "context": 8192, "selected_model": None, "qualification_eligible": False,
                  "candidates": rows}))
'''


def modelfile(weights=WEIGHTS, renderer="qwen3.5", sources=1):
    lines = ["# Modelfile generated by \"ollama show\""]
    lines += [f"FROM /var/lib/ollama/models/blobs/sha256-{weights}"] * sources
    lines += ["TEMPLATE {{ .Prompt }}"]
    if renderer:
        lines += [f"RENDERER {renderer}", f"PARSER {renderer}"]
    return "\n".join(lines + ["PARAMETER top_k 20"]) + "\n"


class FakeOllama:
    """A loopback HTTP service with Ollama's endpoints and a request log."""

    def __init__(self):
        self.requests = []
        self.models = {}          # name -> modelfile
        self.blobs = set()
        self.reply = "Miguel de Cervantes wrote **Don Quixote**."
        self.chat_status = 200
        fake = self

        class Handler(BaseHTTPRequestHandler):
            def log_message(self, *args):
                pass

            def _send(self, status, body=None):
                data = b"" if body is None else json.dumps(body).encode()
                self.send_response(status)
                self.send_header("Content-Length", str(len(data)))
                self.end_headers()
                if self.command != "HEAD":
                    self.wfile.write(data)

            def _body(self):
                size = int(self.headers.get("Content-Length") or 0)
                return self.rfile.read(size)

            def do_GET(self):
                fake.requests.append(("GET", self.path, None))
                if self.path == "/api/version":
                    return self._send(200, {"version": "0.0.0"})
                if self.path == "/api/tags":
                    return self._send(200, {"models": [{"name": n} for n in fake.models]})
                self._send(404, {})

            def do_HEAD(self):
                fake.requests.append(("HEAD", self.path, None))
                digest = self.path.rsplit("/", 1)[-1]
                self._send(200 if digest in fake.blobs else 404)

            def do_POST(self):
                raw = self._body()
                if self.path.startswith("/api/blobs/"):
                    fake.requests.append(("POST", self.path, len(raw)))
                    fake.blobs.add(self.path.rsplit("/", 1)[-1])
                    return self._send(201)
                body = json.loads(raw or b"{}")
                fake.requests.append(("POST", self.path, body))
                if self.path == "/api/show":
                    if body.get("model") not in fake.models:
                        return self._send(404, {"error": "not found"})
                    return self._send(200, {"modelfile": fake.models[body["model"]]})
                if self.path == "/api/chat":
                    if fake.chat_status != 200:
                        return self._send(fake.chat_status, {"error": "boom"})
                    return self._send(200, {"message": {"role": "assistant", "content": fake.reply}})
                if self.path == "/api/create":
                    digest = body["files"]["model.gguf"].removeprefix("sha256:")
                    fake.models[body["model"]] = modelfile(digest, body.get("renderer"))
                    return self._send(200, {"status": "success"})
                self._send(404, {})

        self.server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        self.url = f"http://127.0.0.1:{self.server.server_address[1]}"
        self.thread = threading.Thread(target=self.server.serve_forever, daemon=True)
        self.thread.start()

    def close(self):
        self.server.shutdown()
        self.server.server_close()

    def posted(self, path):
        return [body for method, where, body in self.requests if method == "POST" and where == path]


class ModelTestCase(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name)
        sizer = self.root / "sizer"
        sizer.write_text(SIZER)
        sizer.chmod(0o755)
        env = {key: value for key, value in os.environ.items() if not key.startswith(("KILIX_", "KITTY_"))}
        env.update(KILIX_CONFIG_HOME=str(self.root / "config"), PLEBIAN_MODEL_SIZER=str(sizer),
                   http_proxy="http://127.0.0.1:9", HTTP_PROXY="http://127.0.0.1:9")
        patcher = mock.patch.dict(os.environ, env, clear=True)
        patcher.start()
        self.addCleanup(patcher.stop)
        self.ollama = FakeOllama()
        self.addCleanup(self.ollama.close)

    def ask(self, question="who wrote Don Quixote?"):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            status = kilix_model.ask(question, self.ollama.url)
        return status, out.getvalue(), err.getvalue()

    def set_up_model(self, text=None):
        self.ollama.models[MODEL.name] = text or modelfile()


class IdentityTests(ModelTestCase):
    def test_only_the_measured_weights_with_their_renderer_count(self):
        self.assertFalse(kilix_model.registered(self.ollama.url, MODEL))  # not there at all
        self.set_up_model()
        self.assertTrue(kilix_model.registered(self.ollama.url, MODEL))
        for name, text in (("other weights", modelfile("0" * 64)),
                           ("no renderer", modelfile(renderer="")),
                           ("other renderer", modelfile(renderer="qwen3")),
                           ("two sources", modelfile(sources=2))):
            with self.subTest(name):
                self.set_up_model(text)
                self.assertFalse(kilix_model.registered(self.ollama.url, MODEL))

    def test_a_pulled_model_under_the_upstream_name_is_not_used(self):
        self.ollama.models["qwen3.5:4b"] = modelfile()
        self.assertNotEqual(MODEL.name, "qwen3.5:4b")
        self.assertFalse(kilix_model.registered(self.ollama.url, MODEL))

    def test_the_service_url_override_is_loopback_only(self):
        for value, expected in (("http://127.0.0.1:5000", "http://127.0.0.1:5000"),
                                ("http://localhost:11", "http://localhost:11"),
                                ("http://example.com:80", kilix_model.OLLAMA),
                                ("https://127.0.0.1:5000", kilix_model.OLLAMA),
                                ("http://127.0.0.1:5000/x", kilix_model.OLLAMA), ("", kilix_model.OLLAMA)):
            with self.subTest(value), mock.patch.dict(os.environ, {kilix_model.URL_OVERRIDE: value}):
                self.assertEqual(kilix_model.service_url(), expected)


class AnswerTests(ModelTestCase):
    def test_a_set_up_model_answers_with_a_label_and_the_measured_request(self):
        self.set_up_model()
        status, out, err = self.ask()
        self.assertEqual(status, 0, err)
        self.assertEqual(out, "Miguel de Cervantes wrote Don Quixote.\n"
                              "Model answer (qwen3.5:4b, on this computer). It can be wrong.\n")
        [body] = self.ollama.posted("/api/chat")
        self.assertEqual(body["model"], "kilix/qwen3.5:4b")
        self.assertIs(body["think"], False)
        self.assertIs(body["stream"], False)
        self.assertEqual(body["options"], {"temperature": 0.7, "top_p": 0.8, "top_k": 20, "min_p": 0,
                                           "presence_penalty": 1.5, "repeat_penalty": 1.0,
                                           "num_predict": 128, "num_ctx": 4096})
        self.assertEqual(body["messages"], [{"role": "system", "content": kilix_model.SYSTEM},
                                            {"role": "user", "content": "who wrote Don Quixote?"}])

    def test_a_bare_i_dont_know_is_a_miss(self):
        self.set_up_model()
        for text in ("I don't know.", "I don't know", " i do not know. "):
            with self.subTest(text):
                self.ollama.reply = text
                status, out, err = self.ask()
                self.assertEqual((status, out), (kilix_model.NOT_USED, ""))
                self.assertIn("the local model does not know", err)
        self.ollama.reply = "I don't know. Dreams are private."
        self.assertEqual(self.ask()[0], 0)  # an explanation is shown

    def test_a_failed_reply_is_an_error(self):
        self.set_up_model()
        self.ollama.chat_status = 500
        status, out, err = self.ask()
        self.assertEqual((status, out), (1, ""))
        self.assertIn("the local model failed (HTTP 500)", err)

    def test_off_means_no_request_at_all(self):
        self.set_up_model()
        kilix_model.set_enabled(False)
        self.assertEqual(self.ask(), (kilix_model.NOT_USED, "", ""))
        self.assertEqual(self.ollama.requests, [])
        kilix_model.set_enabled(True)
        self.assertEqual(self.ask()[0], 0)

    def test_a_damaged_setting_leaves_answers_on(self):
        path = self.root / "config" / kilix_model.SETTING
        path.parent.mkdir(parents=True)
        for text in ("{", '{"schema": "other", "enabled": false}', '{"enabled": false}', "[]"):
            with self.subTest(text):
                path.write_text(text)
                self.assertTrue(kilix_model.enabled())

    def test_a_computer_no_model_fits_hears_nothing(self):
        for state in ("set up", "not set up"):
            with self.subTest(state), mock.patch.dict(os.environ, {"FAKE_SIZER_VERDICT": "too-large"}):
                if state == "set up":
                    self.set_up_model()
                self.assertEqual(self.ask(), (kilix_model.NOT_USED, "", ""))
                self.assertEqual(self.ollama.posted("/api/chat"), [])
        with mock.patch.dict(os.environ, {"PLEBIAN_MODEL_SIZER": str(self.root / "missing")}):
            self.assertEqual(self.ask(), (kilix_model.NOT_USED, "", ""))

    def test_a_model_that_fits_but_is_not_set_up_says_how(self):
        status, out, err = self.ask()
        self.assertEqual((status, out), (kilix_model.NOT_USED, ""))
        self.assertIn("kilix ask --model-answers setup", err)
        self.assertIn("qwen3.5:4b, 3.2 GiB", err)
        self.assertEqual(self.ollama.posted("/api/chat"), [])

    def test_a_stopped_service_is_named(self):
        self.ollama.close()
        status, out, err = self.ask()
        self.assertEqual((status, out), (kilix_model.NOT_USED, ""))
        self.assertIn("Ollama) is not running", err)

    def test_markdown_emphasis_is_dropped_and_arithmetic_kept(self):
        for text, shown in (("**Paris** is the capital.", "Paris is the capital."),
                            ("*Hamlet*, by Shakespeare.", "Hamlet, by Shakespeare."),
                            ("2 * 3 * 4 is 24.", "2 * 3 * 4 is 24."),
                            ("* first\n* second", "* first\n* second")):
            with self.subTest(text):
                self.assertEqual(kilix_model.plain(text), shown)


class SetupTests(ModelTestCase):
    def asset(self):
        folder = self.root / "asset"
        (folder / "blobs").mkdir(parents=True)
        for layer in (MODEL.weights, MODEL.license, MODEL.params):
            path = folder / "blobs" / layer.sha256
            if layer is MODEL.params:
                path.write_text('{"temperature":1,"top_k":20}')
            elif layer is MODEL.license:
                path.write_text("Apache License text")
            else:
                path.write_bytes(b"GGUF")
        return folder

    def sizes(self):
        """The fake asset's real sizes in place of the pinned ones."""
        folder = self.asset()
        layers = {}
        for name in ("weights", "license", "params"):
            layer = getattr(MODEL, name)
            layers[name] = kilix_model.Layer(layer.media, layer.sha256,
                                             (folder / "blobs" / layer.sha256).stat().st_size)
        return folder, kilix_model.Admitted(**{**MODEL.__dict__, **layers})

    def test_register_uploads_missing_blobs_and_creates_the_measured_model(self):
        folder, model = self.sizes()
        self.ollama.blobs.add("sha256:" + model.license.sha256)  # already held
        kilix_model.register(self.ollama.url, model, folder, say=lambda text: None)
        uploads = [where for method, where, _ in self.ollama.requests if method == "POST"
                   and where.startswith("/api/blobs/")]
        self.assertEqual(uploads, ["/api/blobs/sha256:" + model.weights.sha256,
                                   "/api/blobs/sha256:" + model.params.sha256])
        [body] = self.ollama.posted("/api/create")
        self.assertEqual(body["model"], "kilix/qwen3.5:4b")
        self.assertEqual(body["files"], {"model.gguf": "sha256:" + WEIGHTS})
        self.assertEqual((body["renderer"], body["parser"]), ("qwen3.5", "qwen3.5"))
        self.assertEqual(body["parameters"], {"temperature": 1, "top_k": 20})
        self.assertEqual(body["license"], ["Apache License text"])
        self.assertTrue(kilix_model.registered(self.ollama.url, model))

    def test_a_blob_that_changed_size_is_not_uploaded(self):
        folder, model = self.sizes()
        (folder / "blobs" / model.weights.sha256).write_bytes(b"GGUF and more")
        with self.assertRaisesRegex(kilix_model.ModelError, "changed size"):
            kilix_model.register(self.ollama.url, model, folder, say=lambda text: None)
        self.assertEqual(self.ollama.posted("/api/create"), [])

    def test_setup_needs_the_licence_agreed_install(self):
        refused = mock.Mock(returncode=1, stdout="", stderr="no receipt")
        out, err = io.StringIO(), io.StringIO()
        with mock.patch.object(kilix_model.subprocess, "run", return_value=refused) as run, \
                contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            self.assertEqual(kilix_model.setup(self.ollama.url), 1)
        self.assertEqual(run.call_args.args[0][1:], ["models", "verify", "qwen3.5-4b"])
        self.assertIn("kilix models install qwen3.5-4b", err.getvalue())
        self.assertEqual([r for r in self.ollama.requests if r[1].startswith(("/api/blobs", "/api/create"))], [])

    def test_setup_rejects_a_different_installed_version(self):
        report = json.dumps({"verified": "qwen3.5-4b", "version": "0" * 64, "root": str(self.root)})
        other = mock.Mock(returncode=0, stdout=report, stderr="")
        with mock.patch.object(kilix_model.subprocess, "run", return_value=other), \
                contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            self.assertEqual(kilix_model.setup(self.ollama.url), 1)
        self.assertEqual(self.ollama.posted("/api/create"), [])

    def test_a_missing_blob_is_reported_not_raised(self):
        folder, model = self.sizes()
        (folder / "blobs" / model.params.sha256).unlink()
        report = json.dumps({"verified": "qwen3.5-4b", "version": model.version, "root": str(self.root)})
        verified = mock.Mock(returncode=0, stdout=report, stderr="")
        err = io.StringIO()
        with mock.patch.object(kilix_model, "ADMITTED", (model,)), \
                mock.patch.object(kilix_model, "_verify", return_value=folder), \
                mock.patch.object(kilix_model.subprocess, "run", return_value=verified), \
                contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(err):
            self.assertEqual(kilix_model.setup(self.ollama.url), 1)
        self.assertIn("setup failed", err.getvalue())
        self.assertEqual(self.ollama.posted("/api/create"), [])

    def test_setup_of_a_set_up_model_changes_nothing(self):
        self.set_up_model()
        with mock.patch.object(kilix_model.subprocess, "run") as run, \
                contextlib.redirect_stdout(io.StringIO()) as out:
            self.assertEqual(kilix_model.setup(self.ollama.url), 0)
        run.assert_not_called()
        self.assertIn("already set up", out.getvalue())


